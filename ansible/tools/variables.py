#!/usr/bin/env python3
"""Builds docs/variables.md from the comments in the defaults and vault example files.

    python3 tools/variables.py          # check: exit 1 if variables.md is stale or a rule below is broken
    python3 tools/variables.py --write  # rewrite docs/variables.md

The defaults files are the only place a default is written. This script copies them, with the comment
above each setting, into one page, so the page cannot disagree with the code. It also fails when:
  - a setting in a defaults file has no comment (above it, or after it on the same line),
  - a `vault_*` name used in roles/ or group_vars/ is in no vault.yml.example,
  - a setting with no default (`undef(hint=...)`) is missing from group_vars/all/vars.yml.example.

Standard library only. Comment rule: the `#` lines directly above a setting, with no blank line between, describe it.
"""
import re
import sys
from pathlib import Path

ANSIBLE = Path(__file__).resolve().parent.parent
DOC = ANSIBLE.parent / "docs" / "variables.md"

DEFAULTS = ANSIBLE / "group_vars/all/defaults.yml"
ROLE_DEFAULTS = sorted(ANSIBLE.glob("roles/*/defaults/main.yml"))
VAULT_EXAMPLES = [ANSIBLE / "group_vars/all/vault.yml.example", ANSIBLE / "host_vars/vault.yml.example"]
VARS_EXAMPLE = ANSIBLE / "group_vars/all/vars.yml.example"

KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):(?:\s+(.*))?$")
SECTION = re.compile(r"^# --- (.+?) ---")
INLINE_COMMENT = re.compile(r"\s+#\s+(.*)$")
HINT = re.compile(r"undef\(hint=(['\"])(.*?)\1\)")


intros = {}


def parse(path):
    """Returns [{name, value, text, example, section}] for each top-level key in a YAML file.

    Section intros found on the way are stored in the module-level `intros`."""
    entries = []
    comment = []
    section = ""
    seen_key = True
    lines = path.read_text().split("\n")
    for i, line in enumerate(lines):
        if line.startswith("#"):
            found = SECTION.match(line)
            if found:
                section = found.group(1)
                seen_key = False
                comment = []
            else:
                comment.append(line[1:].rstrip())
            continue
        found = KEY.match(line)
        if not found:
            if not line.strip():
                # Prose between a section header and its first setting, set off by a blank line, is the section's intro.
                if comment and not seen_key and section:
                    intros[section] = " ".join(c.strip() for c in comment if c.strip())
                comment = []
            continue
        seen_key = True
        name, rest = found.group(1), found.group(2) or ""
        inline = INLINE_COMMENT.search(rest)
        text_inline = inline.group(1) if inline else ""
        value = INLINE_COMMENT.sub("", rest).strip()
        # A value that continues on the next lines (a block scalar, a list or a mapping) is joined into one line.
        if value in ("", ">-", ">", "|", "|-") or value.startswith(("{", "[")) and not value.endswith(("}", "]")):
            parts = [] if value in ("", ">-", ">", "|", "|-") else [value]
            for nxt in lines[i + 1:]:
                if nxt.startswith((" ", "-")) and nxt.strip() and not nxt.lstrip().startswith("#"):
                    parts.append(nxt.strip())
                elif not nxt.strip() or nxt.startswith("#") or KEY.match(nxt):
                    break
            value = " ".join(parts)
        prose = [c.strip() for c in comment if c.strip() and not c.startswith("   ")]
        example = [c[1:] for c in comment if c.startswith("   ")]
        text = " ".join(prose + ([text_inline] if text_inline else []))
        entries.append({"name": name, "value": value, "text": text, "example": example, "section": section})
        comment = []
    return entries


def render_entry(entry, with_default):
    hint = HINT.search(entry["value"])
    if hint:
        head = f"- `{entry['name']}`: **required**, no default. {entry['text']}"
    elif with_default:
        value = entry["value"] if len(entry["value"]) <= 140 else "(long; see the file)"
        head = f"- `{entry['name']}`: default `{value}`. {entry['text']}"
    else:
        head = f"- `{entry['name']}`: {entry['text']}"
    out = [head.rstrip()]
    if entry["example"]:
        out += ["  ```yaml"] + [f"  {line}" for line in entry["example"]] + ["  ```"]
    return out


def build():
    problems = []
    out = [
        "# Variables",
        "",
        "Generated by `just docs` from the comments in the files named below; do not edit it. To change a default, edit the file it comes from and run `just docs`.",
        "",
        "Where a value comes from, lowest priority first: a role's `defaults/main.yml`, `group_vars/all/defaults.yml`, `group_vars/all/vars.yml` (yours), `host_vars/<host>/vars.yml` (yours, one host). A later one wins. Image versions are in `group_vars/all/versions.yml`; `group_vars/all/derived.yml` holds computed values and is not edited.",
        "",
        "Examples to start from: `group_vars/all/vars.yml.example` (the settings with no default), `host_vars/vars.yml.example` (one host), and the two `vault.yml.example` files (secrets).",
        "",
        "## Shared settings (group_vars/all/defaults.yml)",
    ]
    current = None
    for entry in parse(DEFAULTS):
        if entry["section"] != current:
            current = entry["section"]
            out += ["", f"### {current}" if current else "### General", ""]
            if intros.get(current):
                out += [intros[current], ""]
        if not entry["text"]:
            problems.append(f"{DEFAULTS.relative_to(ANSIBLE)}: {entry['name']} has no comment")
        out += render_entry(entry, True)
    out += ["", "## Settings of one role (roles/<role>/defaults/main.yml)"]
    for path in ROLE_DEFAULTS:
        entries = parse(path)
        if not entries:
            continue
        out += ["", f"### {path.parts[-3]}", ""]
        for entry in entries:
            if not entry["text"]:
                problems.append(f"{path.relative_to(ANSIBLE)}: {entry['name']} has no comment")
            out += render_entry(entry, True)
    out += ["", "## Vault entries (secrets)", "", "Copy the example to `vault.yml` next to it, fill it in and encrypt it (`ansible-vault encrypt`). A name defined in both a host's vault and the shared one takes the host's value."]
    for path in VAULT_EXAMPLES:
        out += ["", f"### {path.relative_to(ANSIBLE).as_posix().replace('.example', '')}", ""]
        for entry in parse(path):
            if not entry["text"]:
                problems.append(f"{path.relative_to(ANSIBLE)}: {entry['name']} has no comment")
            out += render_entry(entry, False)
    return "\n".join(out) + "\n", problems


def other_problems():
    problems = []
    documented = set()
    for path in VAULT_EXAMPLES:
        documented |= {e["name"] for e in parse(path)}
    used = {}
    sources = [p for p in ANSIBLE.glob("roles/**/*") if p.is_file()] + list(ANSIBLE.glob("group_vars/**/*.yml")) + [ANSIBLE / "site.yml", ANSIBLE / "teardown.yml"]
    for path in sources:
        if path.name == "vault.yml":
            continue
        try:
            text = path.read_text()
        except UnicodeDecodeError:
            continue
        for name in re.findall(r"\bvault_[a-z0-9_]+\b", text):
            used.setdefault(name, path.relative_to(ANSIBLE))
    for name, where in sorted(used.items()):
        if name not in documented:
            problems.append(f"{name} is used in {where} but is in no vault.yml.example")
    example_keys = {e["name"] for e in parse(VARS_EXAMPLE)}
    for path in [DEFAULTS] + ROLE_DEFAULTS:
        for entry in parse(path):
            if HINT.search(entry["value"]) and entry["name"] not in example_keys:
                problems.append(f"{entry['name']} has no default but is not in {VARS_EXAMPLE.relative_to(ANSIBLE)}")
    return problems


def main():
    page, problems = build()
    problems += other_problems()
    if "--write" in sys.argv:
        DOC.write_text(page)
        print(f"wrote {DOC.relative_to(ANSIBLE.parent)}")
    elif not DOC.exists() or DOC.read_text() != page:
        problems.append(f"{DOC.relative_to(ANSIBLE.parent)} is stale: run `just docs`")
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
